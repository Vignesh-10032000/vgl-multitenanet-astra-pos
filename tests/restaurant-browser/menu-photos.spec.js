import {test,expect} from '@playwright/test';
import {unlockFixture} from './access-helper.js';
import {mkdirSync,readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const output=resolve('test-results/menu-photos');
mkdirSync(output,{recursive:true});
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aV1sAAAAASUVORK5CYII=','base64');

test('MENU-PHOTO-UI-01 offline samples, own-photo priority, removal, warm restart and complete restore',async({page})=>{
  const errors=[],external=[],photoRequests=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{
    const url=request.url();
    if(url.includes('/menu-photos/v1/')) photoRequests.push(url);
    if(!url.startsWith('http://127.0.0.1:5175') && !url.startsWith('data:') && !url.startsWith('blob:')) external.push(url);
  });
  await page.goto('/');
  await unlockFixture(page);
  await expect(page.locator('.product-tile')).toHaveCount(36);
  await expect(page.locator('.product-tile img')).toHaveCount(36);
  expect(photoRequests).toHaveLength(22);
  const dimensions=await page.locator('.product-tile img').evaluateAll(async images=>{
    await Promise.all(images.map(image=>{ image.loading='eager'; return image.decode(); }));
    return images.map(image=>({width:image.naturalWidth,height:image.naturalHeight}));
  });
  expect(dimensions.every(image=>image.width>0 && image.height>0 && Math.max(image.width,image.height)<=384)).toBe(true);
  const tile=id=>page.locator(`[data-product-id="${id}"]`);
  const original=await tile('menu-001').locator('img').getAttribute('src');
  expect(await tile('menu-029').locator('img').getAttribute('src')).toBe(original);
  expect(await tile('menu-002').locator('img').getAttribute('src')).not.toBe(original);
  await page.screenshot({path:resolve(output,'billing-desktop.png')});
  await page.setViewportSize({width:732,height:336});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(732);
  await page.screenshot({path:resolve(output,'billing-compact.png')});
  await page.setViewportSize({width:1920,height:1080});
  photoRequests.length=0;
  await page.reload();
  await expect(tile('menu-001').locator('img')).toHaveAttribute('src',original);
  expect(photoRequests).toHaveLength(0);
  await page.locator('[data-nav=products]').click();
  await page.locator('[data-edit-product="menu-001"]').click();
  await page.locator('#product-form [name=photo]').setInputFiles({name:'own-dish.png',mimeType:'image/png',buffer:png});
  await page.locator('#product-form .button-primary').click();
  await expect(page.locator('#product-dialog')).not.toBeVisible();
  await page.locator('[data-nav=billing]').click();
  await expect(tile('menu-001').locator('img')).not.toHaveAttribute('src',original);
  const own=await tile('menu-001').locator('img').getAttribute('src');
  await page.reload();
  await expect(tile('menu-001').locator('img')).toHaveAttribute('src',own);
  await tile('menu-001').click();
  await expect(page.locator('#total-net')).toHaveText('₹178.50');
  await page.locator('.cart-line [aria-label="Remove item"]').click();
  await page.locator('[data-nav=products]').click();
  await page.locator('[data-edit-product="menu-001"]').click();
  await page.locator('#product-form [name=remove_image]').check();
  await page.locator('#product-form .button-primary').click();
  await expect(page.locator('#product-dialog')).not.toBeVisible();
  await page.locator('[data-nav=billing]').click();
  await expect(tile('menu-001').locator('img')).toHaveCount(0);
  await page.locator('[data-nav=settings]').click();
  const wait=page.waitForEvent('download');
  await page.locator('#backup-button').click();
  const backup=resolve(output,'complete-photo-backup.json');
  await (await wait).saveAs(backup);
  const data=JSON.parse(JSON.parse(readFileSync(backup,'utf8')).payload);
  expect(Object.keys(data.files)).toHaveLength(23); // 22 menu images and the owner logo.
  const store=JSON.parse(data.tables.settings.find(row=>row.id==='store').value);
  expect(data.files[store.logo]).toMatch(/^data:image\/jpeg;base64,/);
  expect(data.tables.drafts.some(row=>row.id==='local:bundled-menu-photos-v1')).toBe(true);
  await page.locator('#restore-file').setInputFiles(backup);
  await expect(page.locator('#restore-dialog')).toBeVisible();
  await page.locator('#restore-confirm').fill('RESTORE');
  await page.locator('#restore-button').click();
  await expect(page.locator('#access-screen')).not.toBeVisible();
  await page.locator('[data-nav=billing]').click();
  await expect(tile('menu-001').locator('img')).toHaveCount(0);
  await expect(page.locator('.product-tile img')).toHaveCount(35);
  expect(external).toEqual([]);
  expect(errors).toEqual([]);
});
