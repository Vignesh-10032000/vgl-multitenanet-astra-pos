import { test, expect } from "@playwright/test";
import { unlockFixture } from "./access-helper.js";

test("Regular and Parcel isolate new products, combine with category/search, and retain fixed kg prices after restart", async ({ page }) => {
  await page.goto("/"); await unlockFixture(page);
  await expect(page.locator(".product-tile")).toHaveCount(36);
  const categoryBounds = await page.locator("#category-strip").boundingBox();
  const gridBounds = await page.locator("#pos-product-grid").boundingBox();
  expect(categoryBounds.y + categoryBounds.height).toBeLessThanOrEqual(gridBounds.y);
  await page.locator('[data-nav="products"]').click();
  await page.locator("#product-menu-filter").selectOption("parcel");
  await page.locator("#add-product").click();
  const form = page.locator("#product-form");
  await expect(form.locator('[name="menu_type"]')).toHaveValue("parcel");
  await form.locator('[name="name"]').fill("Owner kg box");
  await form.locator('[name="category"]').fill("Biryani");
  await form.locator('[name="kilograms"]').fill("0.5");
  await form.locator('[name="price"]').fill("230.00");
  await form.locator(".button-primary").click();
  await expect(page.locator("#product-dialog")).toBeHidden();
  await expect(page.locator("#product-list")).toContainText("Owner kg box");
  await page.locator("#product-menu-filter").selectOption("regular");
  await expect(page.locator("#product-list")).not.toContainText("Owner kg box");
  await page.locator('[data-nav="billing"]').click();
  const box = page.locator(".product-tile").filter({ hasText: "Owner kg box" });
  await expect(box).toContainText("0.5 kg");
  await expect(box).toContainText("₹230.00");
  await page.locator("#billing-menu-filter").selectOption("regular");
  await expect(box).toHaveCount(0);
  await expect(page.locator('[data-product-id="menu-001"]')).toBeVisible();
  await expect(page.locator('[data-product-id="menu-029"]')).toHaveCount(0);
  await page.locator("#billing-menu-filter").selectOption("parcel");
  await expect(box).toBeVisible();
  await expect(page.locator('[data-product-id="menu-001"]')).toHaveCount(0);
  await page.locator('[data-category-id="Biryani"]').click();
  await expect(page.locator(".product-tile")).toHaveCount(1);
  await page.locator("#pos-search").fill("Owner kg");
  await expect(page.locator(".product-tile")).toHaveCount(1);
  await box.click();
  await expect(page.locator("#total-net")).toHaveText("₹241.50");
  await expect(page.locator("#draft-status")).toHaveText("Cart saved locally");
  await page.reload();
  await expect(page.locator("#total-net")).toHaveText("₹241.50");
  await page.locator('[data-nav="products"]').click();
  await page.locator("#product-search").fill("Owner kg box");
  await page.locator("[data-edit-product]").click();
  await expect(form.locator('[name="kilograms"]')).toHaveValue("0.5");
  await expect(form.locator('[name="price"]')).toHaveValue("230.00");
  await expect(form.locator('[name="menu_type"]')).toHaveValue("parcel");
  await form.locator('[name="menu_type"]').selectOption("regular");
  await form.locator('[name="price"]').fill("250.00");
  await form.locator(".button-primary").click();
  await expect(page.locator("#product-dialog")).toBeHidden();
  await page.locator('[data-nav="billing"]').click();
  await page.locator("#billing-menu-filter").selectOption("parcel");
  await expect(box).toHaveCount(0);
  await page.locator("#billing-menu-filter").selectOption("regular");
  await expect(box).toContainText("₹250.00");
  await page.screenshot({ path: "test-results/product-options-billing.png" });
});

test("editing legacy half-kg portion preserves its price and label; kilogram validation can be corrected", async ({ page }) => {
  await page.goto("/"); await unlockFixture(page);
  await page.locator('[data-nav="products"]').click();
  await page.locator('[data-edit-product="menu-032"]').click();
  const form = page.locator("#product-form");
  await expect(form.locator('[name="kilograms"]')).toHaveValue("0.5");
  await expect(form.locator('[name="portion"]')).toHaveValue("1/2 kg");
  await expect(form.locator('[name="price"]')).toHaveValue("230.00");
  await form.locator(".button-primary").click();
  await expect(page.locator("#product-dialog")).toBeHidden();
  await page.locator('[data-edit-product="menu-032"]').click();
  await expect(form.locator('[name="portion"]')).toHaveValue("1/2 kg");
  await form.locator('[name="kilograms"]').fill("0");
  await form.locator(".button-primary").click();
  await expect(page.locator("#product-dialog")).toBeVisible();
  await form.locator('[name="kilograms"]').fill("0.25");
  await form.locator('[name="price"]').fill("125.00");
  await page.screenshot({ path: "test-results/product-options-form.png" });
  await form.locator(".button-primary").click();
  await expect(page.locator("#product-dialog")).toBeHidden();
  await page.locator('[data-nav="billing"]').click();
  await expect(page.locator('[data-product-id="menu-032"]')).toContainText("0.25 kg");
  await expect(page.locator('[data-product-id="menu-032"]')).toContainText("₹125.00");
});
