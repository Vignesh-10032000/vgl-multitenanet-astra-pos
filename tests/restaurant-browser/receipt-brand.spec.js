import { test, expect } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { unlockInclusiveFixture as unlockFixture } from "./access-helper.js";

const output = resolve("test-results/receipt-brand-2026-11-01");
mkdirSync(output, { recursive: true });
test.use({ deviceScaleFactor: 2 });

test("RECEIPT-UI-01 owner reference hierarchy, new offline logo, exact GST and unchanged reprint", async ({ page }) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.clock.setFixedTime(new Date("2026-09-30T18:30:00.000Z"));
  await page.goto("/");
  await unlockFixture(page);
  const logo = page.locator("#nav-logo");
  await expect(logo).toBeVisible();
  await expect(logo).toHaveAttribute("src", /^data:image\/jpeg;base64,/);
  await logo.evaluate(image => image.decode());
  await page.locator('[data-nav="settings"]').click();
  await page.locator('#settings-form [name="round_rupee"]').check();
  await page.locator('#settings-form .button-primary').click();
  await page.locator('[data-nav="billing"]').click();
  await page.locator("#add-billing-customer").click();
  await page.locator("#customer-name").fill("Pollachi");
  await page.locator("#customer-phone").fill("123");
  await page.locator('#customer-form .button-primary').click();
  await page.locator('[data-product-id="menu-001"]').click();
  await page.locator("#order-discount").fill("0.51");
  await expect(page.locator("#total-net")).toHaveText("₹169.00");
  await page.locator("#pay-button").click();
  await page.locator("#complete-sale").click();
  const receipt = page.locator("#receipt-preview .receipt-paper");
  await expect(receipt).toBeVisible();
  await expect(receipt.locator(".receipt-meta")).toHaveText(/Bill: AR\/2627\/0000011\/10\/2026, 12:00:00 amCustomer: Pollachi \/ 123/);
  await expect(receipt.locator("thead")).toHaveText("ITEMQTYRATEAMOUNT");
  await expect(receipt.locator(".receipt-breakdown")).toHaveText("Discount: ₹0.51CGST 2.5%: ₹4.03SGST 2.5%: ₹4.04Round off: ₹-0.49");
  await expect(receipt.locator(".net")).toHaveText("TOTAL₹169.00");
  await expect(receipt.locator(".receipt-settlement")).toHaveCount(0);
  await receipt.locator(".receipt-logo").evaluate(image => image.decode());
  expect(await receipt.locator(".receipt-logo").getAttribute("src")).toBe(await logo.getAttribute("src"));
  await receipt.screenshot({ path: resolve(output, "reference-match.png") });
  const html = await receipt.innerHTML();
  await page.evaluate(() => { window.print = () => {}; });
  await page.locator("#print-receipt").click();
  await expect(page.locator("#print-status")).toContainText("Print submitted. Check the paper output");
  await page.emulateMedia({ media: "print" });
  const printPaper = page.locator("#print-document .receipt-paper");
  await expect(printPaper).toBeVisible();
  const bounds = await printPaper.boundingBox();
  expect(bounds.width).toBeLessThanOrEqual(80 / 25.4 * 96);
  const overflow = await printPaper.evaluate(paper => paper.scrollWidth > paper.clientWidth);
  expect(overflow).toBe(false);
  await page.pdf({ path: resolve(output, "reference-match-80mm.pdf"), width: "80mm", height: `${(bounds.height + 2) / 96 * 25.4}mm`, printBackground: true, margin: { top: 0, bottom: 0, left: 0, right: 0 } });
  await page.emulateMedia({ media: "screen" });
  await page.locator("#receipt-dialog [data-close]").click();
  await page.reload();
  await page.locator("#last-receipt").click();
  await expect(receipt).toBeVisible();
  expect(await receipt.innerHTML()).toBe(html);
  expect(errors).toEqual([]);
});

test("BRAND-UI-02 logo removal survives restart and a later custom upload wins", async ({ page }) => {
  await page.goto("/");
  await unlockFixture(page);
  await expect(page.locator("#nav-logo")).toBeVisible();
  await page.locator('[data-nav="settings"]').click();
  await page.locator('#settings-form [name="remove_logo"]').check();
  await page.locator('#settings-form .button-primary').click();
  await expect(page.locator('#settings-form .button-primary')).toBeEnabled();
  await expect(page.locator("#nav-logo")).toBeHidden();
  await page.reload();
  await expect(page.locator("#nav-logo")).toBeHidden();
  await page.locator('[data-nav="settings"]').click();
  await page.locator('#settings-form [name="logo"]').setInputFiles(resolve("resources/branding/2026-11-01/owner-logo-original.jpeg"));
  await page.locator('#settings-form .button-primary').click();
  await expect(page.locator('#settings-form .button-primary')).toBeEnabled();
  await expect(page.locator("#nav-logo")).toBeVisible();
  const uploaded = await page.locator("#nav-logo").getAttribute("src");
  await page.reload();
  await expect(page.locator("#nav-logo")).toHaveAttribute("src", uploaded);
});
